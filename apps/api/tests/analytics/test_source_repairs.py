class RepairQuery(Query):
    def insert(self, values):
        self.mode, self.values = 'insert', values
        return self

    def execute(self):
        if self.mode != 'insert':
            return super().execute()
        self.client.calls.append((self.table,self.mode,self.columns,self.bounds))
        if self.client.fail_table == self.table:
            self.client.fail_table = None
            raise RuntimeError('private fictional failure')
        rows = self.values if isinstance(self.values,list) else [self.values]
        for value in deepcopy(rows):
            if self.table == 'audit_events':
                assert 'id' not in value, 'audit identity is generated by Postgres'
                value['id'] = len(self.client.tables['audit_events'])+1
            if self.table == 'lers':
                previous = next((row for row in self.client.tables['lers']
                                 if row['is_current'] and row.get('response_id')==value['response_id']),None)
                if previous:
                    previous.update(is_current=False,superseded_by=value['id'])
                    value['revision'] = previous['revision']+1
                value['created_at'] = NOW
                for row in self.client.tables['analytics_results']:
                    row['is_stale'] = True
            self.client.tables.setdefault(self.table,[]).append(value)
        from types import SimpleNamespace
        return SimpleNamespace(data=deepcopy(rows))


class RepairClient(Client):
    def table(self,name):
        return RepairQuery(self,name)


