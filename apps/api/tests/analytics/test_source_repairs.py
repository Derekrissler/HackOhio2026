def test_apply_preserves_originals_and_scores_and_is_idempotent():
    client = fixture()
    original = deepcopy(client.tables['lers'])
    scores = deepcopy(client.tables['responses'])
    plan = plan_for(client)
    with pytest.raises(ValueError,match='serialized'):
        apply_plan(client,plan)
    result = apply_plan(client,plan,exclusive_course_access=True)
    assert result['persisted'] and result['ler_revisions']==4
    assert client.tables['responses']==scores
    for old in original:
        actual = next(r for r in client.tables['lers'] if r['id']==old['id'])
        assert {k:v for k,v in actual.items() if k not in ('is_current','superseded_by')} == {k:v for k,v in old.items() if k not in ('is_current','superseded_by')}
        assert not actual['is_current']
    current = [r for r in client.tables['lers'] if r['is_current']]
    assert len(current)==4 and all(r['revision']==2 for r in current)
    counts = {name:len(rows) for name,rows in client.tables.items()}
    apply_plan(client,plan,exclusive_course_access=True)
    assert {name:len(rows) for name,rows in client.tables.items()}==counts
    assert not plan_for(client).revisions
    batch = SupabaseEvidenceRepository(client).load_course(UUID(COURSE))
    records,_,report = _adapt(batch,AnalyticsConfig(class_min_students=2),None)
    assert len(records)==4 and report.selected_independent_scores==4
    assert all(r.errors_analyzed is None for r in records)


