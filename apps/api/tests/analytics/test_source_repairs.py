def plan_for(client,review=None):
    return build_plan(read_source(client,UUID(COURSE)),review)


def reviewed(client):
    plan = plan_for(client)
    ler = plan.source['lers'][0]
    revision = next(r for r in plan.revisions if r['previous_ler_id']==ler['id'])
    ref = next(r['evidence_ref_id'] for r in revision['ler_evidence'] if r['role']=='response')
    review = SourceReview(course_id=COURSE,input_snapshot=plan.input_snapshot,
        reviewer_ref='fictional-reviewer',reviewed_at=NOW,
        classifications=[ClassificationReview(ler_id=ler['id'],revision=ler['revision'],decision='complete',errors=[
            ReviewedError(code='inequality_direction',label='Inequality direction',
                description='The instructor annotation identifies a reversed inequality.',
                evidence_ref_ids=[ref],outcome_ids=[plan.source['outcomes'][0]['id']],privacy_reviewed=True)])])
    return plan_for(client,review)


